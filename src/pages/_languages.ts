export interface Language {
  /** Stable id, used for option keys and localStorage. */
  id: string;
  name: string;
  /** BCP-47 tag, applied to the sentence once it has been revealed. */
  bcp47: string;
  /** Rough family grouping — drives the "hard" distractor picker. */
  family: string;
  /** Writing system — used as a fallback grouping for one-language families. */
  script: string;
  rtl?: boolean;
  /** Other names a typed guess should accept: endonyms, alternates, common variants. */
  aliases?: string[];
  /** The giveaway, shown after answering. */
  tell: string;
  /**
   * Parallel translations of SENTENCE_GLOSSES, same order. Any {name} and {age}
   * placeholders are filled in by the page before the sentence is shown.
   */
  sentences: string[];
}

